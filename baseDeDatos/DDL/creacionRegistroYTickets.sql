CREATE TABLE REGISTRO_DIARIO(
ID_R INT NOT NULL AUTO_INCREMENT,
grupo VARCHAR(50) NOT NULL, 
horaEntrada VARCHAR(50) NOT NULL,
horaFin VARCHAR(255) NOT NULL,
docente VARCHAR(255) NOT NULL,
asignatura VARCHAR(255) NOT NULL,
fecha DATE NOT NULL,
nombreAula VARCHAR(255) NOT NULL,
turno VARCHAR(255) NOT NULL,


CONSTRAINT pk_registro
    PRIMARY KEY (ID_R)
);

CREATE TABLE TICKET (
ID_R INT NOT NULL,
ID_T INT NOT NULL AUTO_INCREMENT,
estado VARCHAR(50) NOT NULL,
nombreEquipo VARCHAR(50) NOT NULL,
nombreAlumno VARCHAR(255) NOT NULL,
descripcionT VARCHAR(255) NOT NULL,
prioridad VARCHAR(255) NOT NULL,


CONSTRAINT pk_ticket
    PRIMARY KEY (ID_T, ID_R)
);

ALTER TABLE TICKET
    ADD CONSTRAINT fk_ticket
    FOREIGN KEY (ID_R)
    REFERENCES REGISTRO_DIARIO (ID_R);

CREATE TABLE DIAGNOSTICO (
    ID_D  INT NOT NULL AUTO_INCREMENT,
    ID_R INT NOT NULL,
    ID_T INT NOT NULL,
    estadoD VARCHAR(50) NOT NULL,
    fechaD DATE NOT NULL,
    descripcionD VARCHAR(255) NOT NULL,
    

    CONSTRAINT pk_diagnostico
        PRIMARY KEY (ID_D)
);

ALTER TABLE DIAGNOSTICO
    ADD CONSTRAINT fk_diagnostico
    FOREIGN KEY (ID_T, ID_R)
    REFERENCES TICKET (ID_T, ID_R);


