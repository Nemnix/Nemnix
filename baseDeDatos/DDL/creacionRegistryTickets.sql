    horaEntrada TIME NOT NULL,
    horaFin TIME NOT NULL,
    docente VARCHAR(100) NOT NULL,
    asignatura VARCHAR(100) NOT NULL,
    fecha DATE NOT NULL,
    nombreAula VARCHAR(50) NOT NULL,
    turno VARCHAR(20) NOT NULL,

CONSTRAINT pk_registro_diario
PRIMARY KEY (ID_R)

);


